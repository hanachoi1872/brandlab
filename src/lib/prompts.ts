export function buildPositioningPrompt(p: ProductInput, hasImages: boolean): string {
  const line = (label: string, value: string) =>
    value.trim() ? `- ${label}: ${value.trim()}` : "";

  const fields = [
    line("제품명", p.name),
    line("카테고리", p.category),
    line("제품 설명", p.description),
    line("가격", p.price),
    line("주요 기능/성분/스펙", p.features),
    line("생각하는 타겟", p.audienceGuess),
    line("인지하는 경쟁사", p.competitors),
    line("자사가 생각하는 강점", p.strengths),
    line("현재 판매 채널", p.channels),
    line("시장", p.market),
    line("기타 참고사항", p.extra),
  ]
    .filter(Boolean)
    .join("\n");

  return `아래 제품의 포지셔닝 전략을 짜주세요.

## 제품 정보
${fields}
${hasImages ? "\n첨부된 이미지는 이 제품의 실제 사진 또는 상세페이지입니다. 패키지, 톤, 가격대가 주는 인상까지 함께 읽고 분석에 반영하세요.\n" : ""}
## 작업 지시

정보가 비어 있는 항목이 있으면 제품 정보와 카테고리 관행으로부터 합리적으로 추론하되, 추론한 부분은 그 사실이 드러나게 쓰세요.

세그먼트는 정확히 3개, 서로 겹치지 않게. 각각 다른 사람이 다른 이유로 사는 그림이어야 합니다.

포지셔닝 문장은 실제로 사내 문서에 붙여넣어도 되는 완성된 문장으로 쓰세요. 그리고 메인과 방향이 확실히 다른 대안 노선 2개를 함께 제시하되, 각 대안이 무엇을 포기하는지 밝히세요.

태그라인 5개는 서로 다른 결이어야 합니다 — 전부 비슷한 톤이면 실패입니다.

마지막 designBrief는 이 포지셔닝을 시각 언어로 옮길 디자이너가 읽을 브리프입니다. 컬러의 방향, 서체의 성격, 사진의 톤, 그리고 이 카테고리에서 흔해빠진 클리셰 중 피해야 할 것을 구체적으로 적으세요.`;
}

