export function buildDesignPrompt(d: DesignInput, imageCount: number): string {
  const ctx = d.positioningContext.trim()
    ? `\n## 이미 확정된 포지셔닝\n${d.positioningContext.trim()}\n\n이 포지셔닝과 어긋나는 디자인은 만들지 마세요. 둘이 충돌하면 포지셔닝이 우선입니다.\n`
    : "";

  const refs =
    imageCount > 0
      ? `첨부된 이미지 ${imageCount}장이 레퍼런스입니다. 이 이미지들을 실제로 뜯어보고 분석하세요 — 색을 직접 읽고, 서체의 성격과 굵기를 보고, 여백이 어떻게 쓰였는지, 요소들이 어디에 정렬돼 있는지 관찰하세요. 여러 장이면 공통으로 흐르는 원리를 찾으세요.`
      : `이미지 레퍼런스는 없고, 아래 무드 설명만 있습니다. 설명에서 시각 언어를 구성하세요.`;

  return `아래 브랜드의 디자인 시스템을 만들어주세요.

## 브랜드
- 브랜드명: ${d.brandName.trim() || "(미정 — 적절한 이름을 제안하세요)"}
- 카테고리: ${d.category.trim() || "(미상)"}
${d.productNote.trim() ? `- 제품 설명: ${d.productNote.trim()}` : ""}
${d.moodNote.trim() ? `- 원하는 무드: ${d.moodNote.trim()}` : ""}
${ctx}
## 레퍼런스
${refs}

## 작업 지시

먼저 레퍼런스를 해부해서 dna를 채우세요. signals에는 인상이 아니라 관찰을 쓰세요.

그 다음 팔레트와 서체를 정합니다. 서체는 주어진 목록에서만 고를 수 있습니다 — 목록에 없는 서체는 렌더링되지 않습니다. displayFont와 bodyFont는 한글 카피를 담으므로 한글 지원 서체 목록에서 고르세요.

hex 색상값은 반드시 #RRGGBB 6자리로 쓰세요.

copy의 모든 문구는 실제 목업에 그대로 들어갑니다. 글자 수 제한을 넘기지 마세요. 브랜드명이 미정이면 wordmark와 brandName에 당신이 제안하는 이름을 쓰세요.

logo.wordmark는 짧아야 합니다 — 워드마크 자리에 12자가 넘어가면 목업이 깨집니다.`;
}
